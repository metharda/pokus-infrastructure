GENERATED_NOTE = "<!-- Generated by tools/gen (make generate). Do not edit by hand. -->"


def front_matter(title: str, audience: list[str], description: str) -> str:
    """Render the front matter of a generated reference page.

    Args:
        title: Page title.
        audience: Reader roles.
        description: One-sentence summary.

    Returns:
        Front matter followed by the generated-file note.
    """
    return (
        "---\n"
        f"title: {title}\n"
        "type: reference\n"
        f"audience: [{', '.join(audience)}]\n"
        'applies_to: {infra: ">=0.1"}\n'
        "last_verified: {date: null, rc: null, by: null}\n"
        f"description: {description}\n"
        "---\n\n"
        f"{GENERATED_NOTE}\n\n"
    )


def _cell(value: Any) -> str:  # noqa: ANN401 - table cell
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, list):
        return ", ".join(str(v) for v in value) or "—"
    if isinstance(value, dict):
        return ", ".join(f"{k}: {_cell(v)}" for k, v in value.items()) or "—"
    text = str(value).replace("|", "\\|").replace("\n", " ")
    text = text.replace("<", "&lt;").replace(">", "&gt;")
    return text or "—"


def table(headers: list[str], rows: list[list[Any]]) -> str:
    """Render a Markdown table.

    Args:
        headers: Column titles.
        rows: Cell values.

    Returns:
        Table text with a trailing newline.
    """
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out.extend("| " + " | ".join(_cell(c) for c in row) + " |" for row in rows)
    return "\n".join(out) + "\n"


def match_text(match: dict[str, Any]) -> str:
    """Describe a support matrix match rule in words.

    Args:
        match: The rule's ``match`` mapping.

    Returns:
        Text such as ``id = ubuntu; version_id = 24.04`` with the keys as code.
    """
    if match.get("any"):
        return "anything else"
    parts = []
    for key, value in match.items():
        shown = ", ".join(value) if isinstance(value, list) else str(value)
        parts.append(f"`{key}` = {shown}")
    return "; ".join(parts)


def support_matrix_page(root: Path) -> str:
    """Render ``docs/support-matrix.md`` from the support matrix.

    Args:
        root: Component root.

    Returns:
        Page text.
    """
    m = resolve_lock_refs(
        jsonable(load_yaml(root / "preflight/support-matrix.yml")),
        jsonable(load_yaml(root / "versions.lock.yml")),
    )
    out = [
        front_matter(
            "Support matrix",
            ["operator", "developer", "reader"],
            "Which distributions, architectures and environments the lab supports, "
            "and how preflight decides.",
        ),
        "# Support matrix\n\n",
        "Generated from `preflight/support-matrix.yml`, which is the single source of the "
        "preflight decision. Tiers: **supported** (full VM tests and reference GPU hardware), "
        "**tested** (full VM tests, GPU paths not hardware-tested), **experimental** (consent "
        "required), **unsupported**. A host's tier is the worst of its OS, architecture and "
        "environment tiers.\n\n",
        "## Distributions\n\nRules are evaluated top to bottom; the first match wins.\n\n",
    ]
    rows = []
    for rule in m["os"]:
        life = rule.get("lifecycle") or {}
        support = life.get("end_of_support")
        rows.append(
            [
                match_text(rule["match"]),
                rule.get("family"),
                rule["tier"],
                rule.get("release_model"),
                rule.get("parent_from"),
                f"until {support}" if support else (life.get("source") and "see source") or None,
                rule.get("reason"),
            ]
        )
    out.append(
        table(
            [
                "Match",
                "Family",
                "Tier",
                "Release model",
                "Parent from",
                "Regular support",
                "Reason",
            ],
            rows,
        )
    )
    out.append("\nLifecycle sources:\n\n")
    for key, text in m.get("lifecycle_sources", {}).items():
        out.append(f"- `{key}`: {text}\n")
    out.append("\n## Families\n\n")
    out.append(
        table(["Family", "Package manager"], [[k, v["pkg"]] for k, v in m["families"].items()])
    )
    out.append("\n## Architectures\n\n")
    out.append(
        table(
            ["Match", "Tier", "Note"],
            [
                [match_text(r["match"]), r["tier"], r.get("note") or r.get("reason")]
                for r in m["arch"]
            ],
        )
    )
    out.append("\n## Environments\n\n")
    out.append(
        table(
            ["Class", "Tier", "Provider", "Note"],
            [
                [k, v["tier"], v.get("provider"), v.get("note") or v.get("reason")]
                for k, v in m["environment"].items()
            ],
        )
    )
    mins = m["minimums"]
    out.append(
        "\n## Minimum hardware\n\nBelow *required* the host is unsupported; "
        "below *recommended* preflight warns.\n\n"
    )
    out.append(
        table(
            ["Resource", "Required", "Recommended"],
            [
                ["Memory (GiB)", mins["memory_gib"]["required"], mins["memory_gib"]["recommended"]],
                [
                    "CPU threads",
                    mins["cpu_threads"]["required"],
                    mins["cpu_threads"]["recommended"],
                ],
                [
                    "Free disk for /var/lib (GiB)",
                    mins["free_disk_gib"]["var_lib"]["required"],
                    mins["free_disk_gib"]["var_lib"]["recommended"],
                ],
                [
                    "Free disk for /srv/pokus (GiB)",
                    mins["free_disk_gib"]["srv_pokus"]["required"],
                    mins["free_disk_gib"]["srv_pokus"]["recommended"],
                ],
            ],
        )
    )
    out.append(
        "\n## Core requirements\n\nFailing any of these makes the host unsupported, unless a "
        "provider rule below resolves it as an operator action.\n\n"
    )
    out.append(
        table(
            ["Requirement", "Values", "Remediation"],
            [
                [f"`{r['id']}`", r.get("values"), r.get("remediation")]
                for r in m["core_requirements"]
            ],
        )
    )
    out.append(f"\n## Storage\n\n{m['storage']['none_reason']}\n\n")
    out.append(
        table(
            ["Order", "Feature", "Backend"],
            [[i + 1, b["feature"], b["backend"]] for i, b in enumerate(m["storage"]["backends"])],
        )
    )
    out.append("\n## Optional features\n\n")
    rows = []
    for name, spec in m["features"].items():
        reqs = [r if isinstance(r, str) else _cell(r) for r in spec["requires"]]
        rows.append(
            [f"`{name}`", reqs, spec["on_missing"], spec.get("only_if_missing"), spec.get("impact")]
        )
    out.append(
        table(["Feature", "Requires", "When missing", "Only matters without", "Impact"], rows)
    )
    out.append("\n## Provider rules\n\n")
    rows = []
    for provider, rules in m.get("provider_rules", {}).items():
        for kind in ("needs_action", "warnings"):
            for r in rules.get(kind, []):
                rows.append(
                    [
                        provider,
                        kind,
                        _cell(r["when"]),
                        r.get("resolves"),
                        r.get("action") or r.get("message"),
                    ]
                )
    out.append(table(["Provider", "Kind", "When", "Resolves", "Text"], rows))
    out.append(test_results_section(root))
    return "".join(out)


STAGE_MARKS = {"passed": "pass", "failed": "**fail**", "skipped": "—"}


def test_results_section(root: Path) -> str:
    """The last ``make test-distros`` result of every target.

    Args:
        root: Component root.

    Returns:
        Markdown section.
    """
    file = test_targets.load(root / "tests/distros/targets.yml")
    recorded = {r["target"]: r for r in test_results.load(root / "tests/distros/results.yml")}
    out = [
        "\n## Last test results\n\n",
        "`make test-distros` ([How to test the distributions](how-to/test-distributions.md)) "
        "bootstraps the lab in a disposable VM per target, runs bootstrap a second time, which "
        "must change nothing, and then `pokus-lab doctor --smoke`. A result counts for "
        f"{test_results.VALID_DAYS} days after its test date (*Valid until*); a target whose "
        "last result failed or has expired counts as untested.\n\n",
    ]
    rows = []
    for t in file.targets:
        record = recorded.get(t.id)
        stages = (record or {}).get("stages") or {}
        variant = t.firewall + (", SELinux enforcing" if t.selinux else "")
        release = f"{t.os_id} {t.version_id}" if t.version_id else t.os_id
        rows.append(
            [
                f"`{t.id}`",
                release,
                variant,
                record["tested_on"] if record else None,
                f"`{str(record['commit'])[:12]}`" if record else None,
                *[STAGE_MARKS.get(stages.get(s, "")) for s in TEST_STAGES],
                test_results.valid_until(record) if record else None,
                test_results.status(record),
            ]
        )
    out.append(
        table(
            ["Target", "Release", "Variant", "Tested on", "Commit"]
            + [TEST_STAGE_TITLES[s] for s in TEST_STAGES]
            + ["Valid until", "Status"],
            rows,
        )
    )
    return "".join(out)


def _option_rows(parser: argparse.ArgumentParser) -> Iterator[list[Any]]:
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction):
            names = ", ".join(f"`{s}`" for s in action.option_strings)
            yield [names, "", "", "show the help and exit"]
            continue
        if not action.option_strings:
            continue
        names = ", ".join(f"`{s}`" for s in action.option_strings)
        if action.choices:
            value = ", ".join(f"`{c}`" for c in action.choices)
        elif action.nargs == 0:
            value = ""
        else:
            value = f"`{action.metavar or action.dest.upper()}`"
        default = action.default if action.default not in (None, False, argparse.SUPPRESS) else ""
        if isinstance(action, argparse._VersionAction):
            default = ""
        yield [names, value, f"`{default}`" if default != "" else "", action.help or ""]


def relative_defaults(parser: argparse.ArgumentParser, root: Path) -> argparse.ArgumentParser:
    """Show defaults inside the checkout relative to it, not as this machine's paths.

    Args:
        parser: The parser; its defaults are changed in place.
        root: Component root (``infra/``).

    Returns:
        The parser.
    """
    prefix = str(root.resolve()) + "/"
    for action in parser._actions:
        if isinstance(action.default, str) and action.default.startswith(prefix):
            action.default = "infra/" + action.default[len(prefix) :]
    return parser


def usage(parser: argparse.ArgumentParser) -> str:
    """The usage line of a parser, independent of the terminal width.

    Args:
        parser: The parser.

    Returns:
        Usage text as ``format_usage`` prints it on an 80-column terminal (78
        columns), without the ``usage:`` prefix.
    """
    formatter = argparse.HelpFormatter(parser.prog, width=78)
    formatter.add_usage(parser.usage, parser._actions, parser._mutually_exclusive_groups)
    return formatter.format_help().replace("usage: ", "", 1).strip()


def cli_page(parser: argparse.ArgumentParser, *, title: str, intro: str) -> str:
    """Render a CLI reference page from an argument parser.

    Args:
        parser: The parser.
        title: Page title.
        intro: First paragraph.

    Returns:
        Page text.
    """
    out = [
        front_matter(title, ["operator", "developer"], f"Every option of {parser.prog}."),
        f"# {title}\n\n{intro}\n\n",
        f"```text\n{usage(parser)}\n```\n\n",
        f"{parser.description}\n\n",
        "## Options\n\n",
        table(["Option", "Value", "Default", "Description"], list(_option_rows(parser))),
    ]
    if parser.epilog:
        out.append(f"\n{parser.epilog} See [Exit codes](../exit-codes.md).\n")
    return "".join(out)


def exit_codes_page(
    meanings: dict[str, tuple[str, str]],
    codes: dict[str, int],
    bootstrap_codes: list[bootstrap.ExitCode],
    lab_rows: list[list[str]],
) -> str:
    """Render ``docs/reference/exit-codes.md``.

    Args:
        meanings: Outcome to ``(meaning, bootstrap behavior)``.
        codes: Outcome to exit code.
        bootstrap_codes: Exit codes of ``bootstrap.sh``.
        lab_rows: ``[code, command, meaning]`` rows of ``pokus-lab``.

    Returns:
        Page text.
    """
    rows = [
        [codes[o], f"`{o}`", m, b]
        for o, (m, b) in sorted(meanings.items(), key=lambda kv: codes[kv[0]])
    ]
    bootstrap_rows = [
        [
            c.code,
            f"`{c.name}`",
            c.title[:1].upper() + c.title[1:],
            c.meaning[:1].upper() + c.meaning[1:],
            f"[Exit code {c.code}](../how-to/troubleshoot.md#exit-code-{c.code})",
        ]
        for c in bootstrap_codes
    ]
    return "".join(
        [
            front_matter(
                "Exit codes", ["operator", "developer"], "Exit codes of the pokus-infra tools."
            ),
            "# Exit codes\n\n",
            "## bootstrap.sh\n\n",
            "`bootstrap.sh` ends with one of these codes. Codes 0, 1 and 2 are the exit code of "
            "`pokus-lab doctor`, which runs last; codes 10 to 40 come from the preflight gate. "
            "Re-running bootstrap after any of them resumes cleanly.\n\n",
            table(["Code", "Constant", "Title", "Meaning", "What to do"], bootstrap_rows),
            "\n## pokus-preflight\n\n",
            "The exit code is the outcome of the support-matrix decision "
            "(see [Support matrix](../support-matrix.md)).\n\n",
            table(["Code", "Outcome", "Meaning", "Bootstrap behavior"], rows),
            "\n## pokus-lab\n\n",
            "`pokus-lab preflight` passes the exit code of pokus-preflight through. "
            "See [Doctor checks](doctor-checks.md) for the severity of every check.\n\n",
            table(["Code", "Command", "Meaning"], lab_rows),
        ]
    )


