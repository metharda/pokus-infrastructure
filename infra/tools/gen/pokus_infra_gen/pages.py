def _schema_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return f"see `{node['$ref'].rsplit('/', 1)[-1]}`"
    if "const" in node:
        return f"constant `{node['const']}`"
    if "enum" in node:
        return "one of " + ", ".join("`null`" if v is None else f"`{v}`" for v in node["enum"])
    t = node.get("type", "any")
    return " or ".join(t) if isinstance(t, list) else str(t)


def schema_rows(node: dict[str, Any], path: str) -> Iterator[list[Any]]:
    """Walk a JSON Schema and yield ``[path, type, required, description]`` rows.

    Args:
        node: Schema node.
        path: Path of the node.

    Yields:
        Table rows.
    """
    required = set(node.get("required", []))
    for key, child in node.get("properties", {}).items():
        child_path = f"{path}.{key}" if path else key
        yield [
            f"`{child_path}`",
            _schema_type(child),
            key in required,
            child.get("description", ""),
        ]
        yield from schema_rows(child, child_path)
        items = child.get("items")
        if isinstance(items, dict) and "properties" in items:
            yield from schema_rows(items, f"{child_path}[]")
    extra = node.get("additionalProperties")
    if isinstance(extra, dict):
        yield [f"`{path}.*`", _schema_type(extra), False, "any key; value as described"]


